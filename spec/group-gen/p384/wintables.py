#!/usr/bin/env python3
"""Generate P-384's compiled-in fixed-base window tables.

Writes, relative to the repository root:

  spec/Spec.P384.Base.fst          the five extra base points 2^{64j} G
  spec/Spec.P384.Win{0..5}.fst     the multiples 0 .. 16 of each, affine
  code/p384/Hacl.P384.Win{0..5}.fst  their Montgomery limbs

Run from spec/group-gen:  python3 p384/wintables.py
The numbers are computed here, but nothing is trusted: every point is
re-checked by F*'s normaliser (on the curve, and equal to the previous
entry plus the base point, or to a chain of 64 doublings).
"""

import os

P = 2**384 - 2**128 - 2**96 + 2**32 - 1
B = 0xb3312fa7e23ee7e4988e056be3f82d19181d9c6efe8141120314088f5013875ac656398d8a2ed19d2a85c8edd3ec2aef
GX = 0xaa87ca22be8b05378eb1c71ef320ad746e1d3b628ba79b9859f741e082542a385502f25dbf55296c3a545e3872760ab7
GY = 0x3617de4a96262c6f5d9e98bf9292dc29f8f41dbd289a147ce9da3113b5f0b8c00a60b1ce1d7e819d7a431d7c90ea0e5f
R = 2**384
NPIECE = 6
W = 64

ROOT = os.path.normpath(os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', '..', '..'))

