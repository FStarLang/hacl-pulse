#!/usr/bin/env python3
"""Generate the Ed25519 base-point comb tables and their proofs.

Usage: python3 spec/group-gen/ed25519/comb.py [repo-root]

Writes spec/Spec.Ed25519.Comb{B,T0..T7,Table}.fst and
code/ed25519/Hacl.Ed25519.CombData{,0..7}.fst."""
import os, sys

p = 2**255 - 19
d = 37095705934669439343138083508754565189542113879843219016388785533085940283555
d2 = (d + d) % p
gx = 15112221349535400772501151409588531511454012693041857206046113283949847762202
gy = 46316835694926478169428394003475163141307993866256225615783033603165251855960
def inv(x): return pow(x, p - 2, p)
def add(P, Q):
    (x1, y1), (x2, y2) = P, Q
    t = d * x1 * x2 * y1 * y2 % p
    return ((x1 * y2 + y1 * x2) * inv(1 + t) % p, (y1 * y2 + x1 * x2) * inv(1 - t) % p)
O = (0, 1)
def smul(n, P):
    R = O
    while n:
        if n & 1: R = add(R, P)
        P = add(P, P); n >>= 1
    return R
G = (gx, gy)


HDR = """(*
   Copyright 2026 Microsoft Research

   Licensed under the Apache License, Version 2.0 (the "License");
   you may not use this file except in compliance with the License.
   You may obtain a copy of the License at

       http://www.apache.org/licenses/LICENSE-2.0

   Unless required by applicable law or agreed to in writing, software
   distributed under the License is distributed on an "AS IS" BASIS,
   WITHOUT WARRANTIES OR CONDITIONS OF ANY KIND, either express or implied.
   See the License for the specific language governing permissions and
   limitations under the License.
*)

"""
NJ, NM, GRP = 32, 9, 4
# pts[j][m] = affine (x, y) of m * 256^j * G
pts = []
for j in range(NJ):
    b = smul(256 ** j, G)
    row = [O, b]
    for m in range(2, NM):
        row.append(add(row[-1], b))
    pts.append(row)

def lit(name, v):
    return ('[@@"opaque_to_smt"]\nlet %s : elem =\n  assert_norm (%d < prime);\n  %d\n\n' % (name, v, v))

def pname(j, m):
    return "b%d" % j if m == 1 else "e%d_%d" % (j, m)

def spec_bases():
    s = HDR
    s += ("(** The comb's thirty-two base points [256^j G], affine, each proved by\n"
          "    the normaliser to be eight doublings of the one before.  Generated\n"
          "    by [spec/group-gen/ed25519/comb.py]; see {!Spec.Ed25519.CombTable}. *)\n"
          "module Spec.Ed25519.CombB\n\nmodule G = Spec.Group.Smul\nmodule SM = Spec.Ed25519.Smul\n"
          "\nopen Spec.Curve25519\nopen Spec.Ed25519\nopen Spec.Ed25519.Group\n\n"
          "#push-options \"--fuel 0 --ifuel 0 --z3rlimit 50\"\n\n")
    for j in range(NJ):
        s += "let n%d : nat = pow2 %d\n\n" % (j, 8 * j)
        x, y = pts[j][1]
        if j == 0:
            s += "let b0 : ext_point = g\n\n"
            s += ("let b0_ok (_: unit) : Lemma (on_curve b0 /\\ point_equal b0 (SM.smul n0 g))\n"
                  "  = g_on_curve ();\n    assert_norm (pow2 0 == 1);\n    SM.smul_one g;\n"
                  "    SM.smul_ok 1 g;\n    point_equal_sym (SM.smul 1 g) g\n\n")
        else:
            s += lit("b%dx" % j, x) + lit("b%dy" % j, y) + lit("b%dt" % j, x * y % p)
            s += "let b%d : ext_point = (b%dx, b%dy, one, b%dt)\n\n" % (j, j, j, j)
            s += ("let b{j}_ok (_: unit) : Lemma (on_curve b{j} /\\ point_equal b{j} (SM.smul n{j} g))\n"
                  "  = assert_norm (on_curve b{j});\n"
                  "    assert_norm (point_equal b{j} (G.dblk SM.eg 8 b{i}));\n"
                  "    b{i}_ok ();\n    g_on_curve ();\n"
                  "    G.dblk_ok SM.eg 8 n{i} g b{i};\n"
                  "    FStar.Math.Lemmas.pow2_plus 8 {e};\n"
                  "    SM.smul_ok n{j} g;\n"
                  "    point_equal_trans b{j} (G.dblk SM.eg 8 b{i}) (SM.smul n{j} g)\n\n").format(j=j, i=j - 1, e=8 * (j - 1))
    s += "#pop-options\n"
    return s

def spec_module(c):
    js = range(GRP * c, GRP * c + GRP)
    s = HDR
    s += "(** Tables %d to %d of the base-point comb, generated by\n    [spec/group-gen/ed25519/comb.py].  Table [j] holds [m 256^j G] for [m] in [0..8],\n    affine, each entry proved by the normaliser to be the previous one\n    plus the table's base point.  See {!Spec.Ed25519.CombTable}. *)\n" % (js[0], js[-1])
    s += "module Spec.Ed25519.CombT%d\n\nmodule SM = Spec.Ed25519.Smul\nmodule CB = Spec.Ed25519.Comb\n" % c
    s += "\nopen Spec.Curve25519\nopen Spec.Ed25519\nopen Spec.Ed25519.Group\nopen Spec.Ed25519.CombB\n\n#push-options \"--fuel 0 --ifuel 0 --z3rlimit 50\"\n\n"
    for j in js:
        s += "(** {2 Table %d} *)\n\n" % j
        s += ("let bq{j} (_: unit) : Lemma (CB.isq b{j} n{j})\n"
              "  = b{j}_ok (); CB.isq_intro b{j} n{j}\n\n"
              "let bq{j}_1 (_: unit) : Lemma (CB.isq b{j} (1 * n{j}))\n"
              "  = bq{j} (); CB.isq_one b{j} n{j}\n\n").format(j=j)
        for m in range(2, NM):
            x, y = pts[j][m]
            nm = pname(j, m)
            s += lit(nm + "x", x) + lit(nm + "y", y) + lit(nm + "t", x * y % p)
            s += "let %s : ext_point = (%sx, %sy, one, %st)\n\n" % (nm, nm, nm, nm)
            pv = pname(j, m - 1)
            pok = "bq%d_1" % j if m == 2 else pv + "_ok"
            s += ("let {nm}_ok (_: unit) : Lemma (CB.isq {nm} ({m} * n{j}))\n"
                  "  = assert_norm (CB.ncheck {nm} {pv} b{j});\n"
                  "    {pok} ();\n    bq{j} ();\n"
                  "    CB.isq_step {pv} b{j} {nm} {m1} n{j}\n\n").format(nm=nm, m=m, m1=m - 1, j=j, pv=pv, pok=pok)
        s += "let tp%d (m: nat { m < 9 }) : ext_point =\n  if m = 0 then point_at_infinity\n" % j
        for m in range(1, NM - 1):
            s += "  else if m = %d then %s\n" % (m, pname(j, m))
        s += "  else %s\n\n" % pname(j, NM - 1)
        for m in range(NM):
            nm = "point_at_infinity" if m == 0 else pname(j, m)
            s += ("let tp{j}_ok{m} (_: unit)\n"
                  "  : Lemma (CB.affine (tp{j} {m}) /\\ CB.isq (tp{j} {m}) ({m} * pow2 {e}))\n").format(j=j, m=m, e=8 * j)
            if m == 0:
                s += "  = CB.isq_zero (0 * pow2 %d)\n\n" % (8 * j)
            else:
                ok = "bq%d_1" % j if m == 1 else nm + "_ok"
                s += "  = %s ();\n    assert (n%d == pow2 %d)\n\n" % (ok, j, 8 * j)
        s += ("let tp{j}_ok (m: nat {{ m < 9 }})\n"
              "  : Lemma (CB.affine (tp{j} m) /\\ CB.isq (tp{j} m) (m * pow2 {e}))\n").format(j=j, e=8 * j)
        for m in range(NM - 1):
            s += "  %s m = %d then tp%d_ok%d ()\n" % ("= if" if m == 0 else "  else if", m, j, m)
        s += "    else (assert (m == 8); tp%d_ok8 ())\n\n" % j
    s += "#pop-options\n"
    return s

def spec_table():
    s = HDR
    s += ("(** The thirty-two tables of the base-point comb, by index: [tp j m] is\n"
          "    an affine representative of [m 256^j G].  Generated by\n"
          "    [spec/group-gen/ed25519/comb.py]; the proofs are in {!Spec.Ed25519.CombT0} and\n"
          "    its seven siblings. *)\nmodule Spec.Ed25519.CombTable\n\n"
          "module SM = Spec.Ed25519.Smul\nmodule CB = Spec.Ed25519.Comb\n")
    for c in range(NJ // GRP):
        s += "module T%d = Spec.Ed25519.CombT%d\n" % (c, c)
    s += "\nopen Spec.Ed25519\nopen Spec.Ed25519.Group\n\n#push-options \"--fuel 0 --ifuel 0 --z3rlimit 50\"\n\n"
    s += "let tp (j: nat { j < 32 }) (m: nat { m < 9 }) : ext_point =\n"
    for j in range(NJ):
        kw = "if" if j == 0 else "else if"
        if j == NJ - 1:
            s += "  else T%d.tp%d m\n\n" % (j // GRP, j)
        else:
            s += "  %s j = %d then T%d.tp%d m\n" % (kw, j, j // GRP, j)
    s += ("let tp_ok (j: nat { j < 32 }) (m: nat { m < 9 })\n"
          "  : Lemma (CB.affine (tp j m) /\\ CB.isq (tp j m) (m * pow2 (8 * j)))\n")
    for j in range(NJ):
        kw = "  = if" if j == 0 else "    else if"
        if j == NJ - 1:
            s += "    else (assert (j == 31); T%d.tp%d_ok m)\n\n" % (j // GRP, j)
        else:
            s += "%s j = %d then T%d.tp%d_ok m\n" % (kw, j, j // GRP, j)
    s += "#pop-options\n"
    return s

def limbs(v):
    return [(v >> (51 * i)) & (2 ** 51 - 1) for i in range(5)]

def niels(P):
    x, y = P
    return [(y + x) % p, (y - x) % p, d2 * (x * y % p) % p]

def data_module():
    s = HDR
    s += ("(** The base-point comb's thirty-two tables, compiled in: one array of\n"
          "    [32 * 9 * 15] limbs, table [j] entry [m] at [135 j + 15 m], each\n"
          "    entry [y + x], [y - x] and [2 d x y] of [m 256^j G] in five\n"
          "    fifty-one-bit limbs apiece.  Generated by [spec/group-gen/ed25519/comb.py];\n"
          "    {!Hacl.Ed25519.CombData0} and its siblings prove what it holds. *)\n"
          "module Hacl.Ed25519.CombData\n\nmodule Seq = FStar.Seq\nmodule L = FStar.List.Tot\n"
          "module G = Pulse.Lib.GlobalArray\nmodule S64 = Hacl.Secret.UInt64\n\n"
          "#push-options \"--fuel 0 --ifuel 0 --z3rlimit 100\"\n\n")
    s += "[@@\"opaque_to_smt\"]\nlet tbl_list : list S64.t = [\n"
    rows = []
    for j in range(NJ):
        for m in range(NM):
            for v in niels(pts[j][m]):
                rows.append("  " + "; ".join("S64.classify 0x%xuL" % l for l in limbs(v)))
    s += ";\n".join(rows) + "\n]\n\n"
    s += ("let len_ok (_: unit) : Lemma (L.length tbl_list == 4320)\n"
          "  = assert_norm (L.length tbl_list == 4320)\n\n"
          "[@@\"opaque_to_smt\"; FStar.Custard.no_specialize]\n"
          "let tbl_seq : Seq.seq S64.t = Seq.seq_of_list tbl_list\n\n"
          "let tbl_arr : (a: G.static_array S64.t\n"
          "                  { G.static_array_elems a == tbl_seq /\\\n"
          "                    Seq.length (G.static_array_elems a) == 4320 })\n"
          "  = reveal_opaque (`%tbl_seq) tbl_seq;\n"
          "    len_ok ();\n"
          "    G.mk_static_array tbl_list\n\n#pop-options\n")
    return s

def data_proof(c):
    js = range(GRP * c, GRP * c + GRP)
    s = HDR
    s += ("(** What tables %d to %d of {!Hacl.Ed25519.CombData} hold: one\n"
          "    normaliser call per entry.  Generated by [spec/group-gen/ed25519/comb.py]. *)\n"
          "module Hacl.Ed25519.CombData%d\n\nopen Hacl.Ed25519.CombEnt\nopen Hacl.Ed25519.CombData\n\n"
          "module CT = Spec.Ed25519.CombTable\n\n"
          "#push-options \"--fuel 0 --ifuel 0 --z3rlimit 100\"\n\n") % (js[0], js[-1], c)
    for j in js:
        for m in range(NM):
            s += ("let ent_{j}_{m} (_: unit) : Lemma (lent tbl_list {j} {m})\n"
                  "  = len_ok ();\n    assert_norm (nlit tbl_list {j} {m} (CT.tp {j} {m}));\n"
                  "    nent_lit tbl_list {j} {m} (CT.tp {j} {m})\n\n").format(j=j, m=m)
        s += "let tbl_%d (_: unit) : Lemma (forall (m: nat { m < 9 }). lent tbl_list %d m)\n  = " % (j, j)
        s += "; ".join("ent_%d_%d ()" % (j, m) for m in range(NM)) + "\n\n"
    s += "let grp_ok (_: unit)\n  : Lemma (%s)\n  = %s\n\n" % (
        " /\\\n           ".join("(forall (m: nat { m < 9 }). lent tbl_list %d m)" % j for j in js),
        "; ".join("tbl_%d ()" % j for j in js))
    s += "#pop-options\n"
    return s


root = sys.argv[1] if len(sys.argv) > 1 else os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..", "..")
for c in range(NJ // GRP):
    open(os.path.join(root, "spec/Spec.Ed25519.CombT%d.fst" % c), "w").write(spec_module(c))
    open(os.path.join(root, "code/ed25519/Hacl.Ed25519.CombData%d.fst" % c), "w").write(data_proof(c))
open(os.path.join(root, "spec/Spec.Ed25519.CombB.fst"), "w").write(spec_bases())
open(os.path.join(root, "spec/Spec.Ed25519.CombTable.fst"), "w").write(spec_table())
open(os.path.join(root, "code/ed25519/Hacl.Ed25519.CombData.fst"), "w").write(data_module())
