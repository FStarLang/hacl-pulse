/* HPKE (RFC 9180) against the CFRG test vectors.
 *
 * The four shipped ciphersuites, in Base mode, from test-vectors.json.  Each
 * one is checked six ways:
 *
 *   - SetupBaseS with the vector's ephemeral private key must reproduce the
 *     vector's encapsulation, key, base nonce and exporter secret;
 *   - SetupBaseR on that encapsulation must reproduce the same context;
 *   - the single-shot Seal must reproduce the vector's first ciphertext and
 *     tag, which are the ones sealed at sequence number zero;
 *   - the single-shot Open must recover the plaintext;
 *   - Open must reject a ciphertext with one bit flipped;
 *   - Open must reject a tag with one bit flipped.
 *
 * Only the first of each vector's encryptions is used: the C surface seals
 * one message per context, so sequence numbers above zero are exercised on
 * the F* side instead.
 *
 * files/gen_hpke_test.py generated this file.
 */
#include <stdbool.h>
#include <stdint.h>
#include <stdio.h>
#include <string.h>

#include "Hacl.h"
#include "test_util.h"

typedef bool (*setup_s_t)(uint8_t *, uint8_t *, uint8_t *, uint64_t *,
                          uint8_t *, uint8_t *, uint8_t *, uint8_t *, size_t);
typedef bool (*setup_r_t)(uint8_t *, uint8_t *, uint64_t *, uint8_t *,
                          uint8_t *, uint8_t *, uint8_t *, size_t);
typedef bool (*seal_t)(uint8_t *, uint8_t *, uint8_t *, uint8_t *, uint8_t *,
                       uint8_t *, size_t, uint8_t *, size_t, uint8_t *, size_t);
typedef bool (*open_t)(uint8_t *, uint8_t *, uint8_t *, uint8_t *, size_t,
                       uint8_t *, size_t, uint8_t *, size_t, uint8_t *);

struct suite {
  const char *name;
  setup_s_t setup_s;
  setup_r_t setup_r;
  seal_t seal;
  open_t open;
  size_t pk_len;   /* encapsulation and public key */
  size_t key_len;  /* AEAD key */
  size_t kdf_len;  /* exporter secret */
  const uint8_t *skE, *pkR, *skR, *info, *key, *base_nonce, *exporter, *enc;
  const uint8_t *aad, *pt, *ct, *tag;
  size_t info_len, aad_len, pt_len;
};

static uint8_t enc[65];
static uint8_t key[32];
static uint8_t nonce[12];
static uint8_t exporter[64];
static uint8_t ct[256];
static uint8_t tag[16];
static uint8_t pt[256];
static uint64_t sq;

static int one(const struct suite *s) {
  int r = 0;
  char label[96];

  printf("  %s\n", s->name);

  memset(enc, 0, sizeof enc);
  memset(key, 0, sizeof key);
  memset(nonce, 0, sizeof nonce);
  memset(exporter, 0, sizeof exporter);
  sq = 1;
  if (!s->setup_s(enc, key, nonce, &sq, exporter, (uint8_t *)s->skE,
                  (uint8_t *)s->pkR, (uint8_t *)s->info, s->info_len)) {
    printf("  FAIL %s setupBaseS\n", s->name);
    return 1;
  }
  snprintf(label, sizeof label, "%s enc", s->name);
  r |= check(label, enc, s->enc, s->pk_len);
  snprintf(label, sizeof label, "%s key", s->name);
  r |= check(label, key, s->key, s->key_len);
  snprintf(label, sizeof label, "%s base_nonce", s->name);
  r |= check(label, nonce, s->base_nonce, 12);
  snprintf(label, sizeof label, "%s exporter", s->name);
  r |= check(label, exporter, s->exporter, s->kdf_len);
  if (sq != 0) {
    printf("  FAIL %s sequence number not zero\n", s->name);
    r |= 1;
  }

  memset(key, 0, sizeof key);
  memset(nonce, 0, sizeof nonce);
  memset(exporter, 0, sizeof exporter);
  if (!s->setup_r(key, nonce, &sq, exporter, (uint8_t *)s->enc,
                  (uint8_t *)s->skR, (uint8_t *)s->info, s->info_len)) {
    printf("  FAIL %s setupBaseR\n", s->name);
    return r | 1;
  }
  snprintf(label, sizeof label, "%s key (receiver)", s->name);
  r |= check(label, key, s->key, s->key_len);
  snprintf(label, sizeof label, "%s base_nonce (receiver)", s->name);
  r |= check(label, nonce, s->base_nonce, 12);
  snprintf(label, sizeof label, "%s exporter (receiver)", s->name);
  r |= check(label, exporter, s->exporter, s->kdf_len);

  memset(ct, 0, sizeof ct);
  memset(tag, 0, sizeof tag);
  if (!s->seal(enc, ct, tag, (uint8_t *)s->skE, (uint8_t *)s->pkR,
               (uint8_t *)s->info, s->info_len, (uint8_t *)s->aad, s->aad_len,
               (uint8_t *)s->pt, s->pt_len)) {
    printf("  FAIL %s seal\n", s->name);
    return r | 1;
  }
  snprintf(label, sizeof label, "%s ct", s->name);
  r |= check(label, ct, s->ct, s->pt_len);
  snprintf(label, sizeof label, "%s tag", s->name);
  r |= check(label, tag, s->tag, 16);

  memset(pt, 0, sizeof pt);
  if (!s->open(pt, (uint8_t *)s->enc, (uint8_t *)s->skR, (uint8_t *)s->info,
               s->info_len, (uint8_t *)s->aad, s->aad_len, (uint8_t *)s->ct,
               s->pt_len, (uint8_t *)s->tag)) {
    printf("  FAIL %s open\n", s->name);
    return r | 1;
  }
  snprintf(label, sizeof label, "%s pt", s->name);
  r |= check(label, pt, s->pt, s->pt_len);

  memcpy(ct, s->ct, s->pt_len);
  ct[0] ^= 1;
  if (s->open(pt, (uint8_t *)s->enc, (uint8_t *)s->skR, (uint8_t *)s->info,
              s->info_len, (uint8_t *)s->aad, s->aad_len, ct, s->pt_len,
              (uint8_t *)s->tag)) {
    printf("  FAIL %s open accepted a corrupted ciphertext\n", s->name);
    r |= 1;
  } else {
    printf("  ok   %s rejects a corrupted ciphertext\n", s->name);
  }

  memcpy(tag, s->tag, 16);
  tag[0] ^= 1;
  if (s->open(pt, (uint8_t *)s->enc, (uint8_t *)s->skR, (uint8_t *)s->info,
              s->info_len, (uint8_t *)s->aad, s->aad_len, (uint8_t *)s->ct,
              s->pt_len, tag)) {
    printf("  FAIL %s open accepted a corrupted tag\n", s->name);
    r |= 1;
  } else {
    printf("  ok   %s rejects a corrupted tag\n", s->name);
  }

  return r;
}

