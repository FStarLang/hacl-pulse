/* FrodoKEM -- eFrodoKEM, the unsalted variant -- against the NIST KAT.
 *
 * The coins below are the first two draws of the NIST KAT DRBG seeded with
 * the first seed of PQCkemKAT_*_shake.rsp, so for Frodo640, Frodo976 and
 * Frodo1344 the public key, secret key, ciphertext and shared secret here
 * are the first record of the published known-answer test file, byte for
 * byte.  Frodo64 is a toy set with no published vectors; its values come
 * from the same reference implementation, run on the same coins.
 *
 * Keys and ciphertexts run to tens of kilobytes, so what is stored is a
 * SHA3-256 digest of each; the shared secret, which is at most thirty-two
 * bytes, is stored whole.  files/gen_frodo.py generated all of it and
 * reproduces the three published records from the seed.
 *
 * Each parameter set is checked five ways: the public key, the secret key
 * and the ciphertext against their digests, the encapsulated shared secret
 * against the vector, and decapsulation both of the real ciphertext (which
 * must give the same secret back) and of a ciphertext with one bit flipped
 * (which must give the implicit-rejection secret, also a vector -- not
 * merely something different, and not a failure code).
 */
#include <stdint.h>
#include <stdio.h>
#include <string.h>

#include "Hacl.h"
#include "test_util.h"

static uint8_t pk[21520];
static uint8_t sk[43088];
static uint8_t ct[21632];
static uint8_t ss[32];
static uint8_t ss2[32];
static uint8_t bad[21632];
static uint8_t digest[32];

typedef void (*keypair_t)(uint8_t *, uint8_t *, uint8_t *);
typedef void (*enc_t)(uint8_t *, uint8_t *, uint8_t *, uint8_t *);
typedef void (*dec_t)(uint8_t *, uint8_t *, uint8_t *);

static int check_digest(const char *name, const uint8_t *buf, size_t len,
                        const uint8_t *expected) {
  Hacl_Hash_SHA3_sha3_256(digest, (uint8_t *)buf, len);
  return check(name, digest, expected, 32);
}

static int one(const char *name, keypair_t keypair, enc_t enc, dec_t dec,
               size_t pkb, size_t skb, size_t ctb, size_t ssb,
               const uint8_t *coins, const uint8_t *mu, const uint8_t *pkd,
               const uint8_t *skd, const uint8_t *ctd, const uint8_t *ssx,
               const uint8_t *ssbad) {
  int r = 0;
  char label[64];

  keypair(pk, sk, (uint8_t *)coins);
  enc(ct, ss, pk, (uint8_t *)mu);

  snprintf(label, sizeof label, "%s pk", name);
  r |= check_digest(label, pk, pkb, pkd);
  snprintf(label, sizeof label, "%s sk", name);
  r |= check_digest(label, sk, skb, skd);
  snprintf(label, sizeof label, "%s ct", name);
  r |= check_digest(label, ct, ctb, ctd);
  snprintf(label, sizeof label, "%s ss", name);
  r |= check(label, ss, ssx, ssb);

  memset(ss2, 0, sizeof ss2);
  dec(ss2, ct, sk);
  snprintf(label, sizeof label, "%s roundtrip", name);
  r |= check(label, ss2, ssx, ssb);

  memcpy(bad, ct, ctb);
  bad[0] ^= 1U;
  memset(ss2, 0, sizeof ss2);
  dec(ss2, bad, sk);
  snprintf(label, sizeof label, "%s rejection", name);
  r |= check(label, ss2, ssbad, ssb);

  return r;
}


