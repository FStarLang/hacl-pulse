static void hex(char *dst, const uint8_t *src, size_t n) {
  for (size_t i = 0; i < n; i++)
    sprintf(dst + 2 * i, "%02x", src[i]);
}

static void report(const char *what, size_t idx, const uint8_t *out,
                   size_t nn, const char *expected) {
  char got[129];
  hex(got, out, nn);
  if (strcmp(got, expected) != 0) {
    printf("  FAIL %s vector %zu\n    got      %s\n    expected %s\n", what,
           idx, got, expected);
    failures++;
  }
}

static void one_shot(size_t idx, const struct vec *v) {
  uint8_t out[64];
  uint8_t *salt = v->salted ? saltbuf : (uint8_t *)zeros;
  uint8_t *pers = v->personal ? persbuf : (uint8_t *)zeros;
  memset(out, 0, sizeof out);
  if (v->alg == 'b')
    Hacl_Hash_Blake2_Named_blake2b_params(out, v->nn, keybuf, v->kl, buf,
                                          v->ml, salt, pers, v->fanout,
                                          v->depth, v->leaf, v->off, v->nd,
                                          v->il);
  else
    Hacl_Hash_Blake2_Named_blake2s_params(out, v->nn, keybuf, v->kl, buf,
                                          v->ml, salt, pers, v->fanout,
                                          v->depth, v->leaf, v->off, v->nd,
                                          v->il);
  report("one-shot", idx, out, v->nn, v->expected);
}

static void streaming(size_t idx, const struct vec *v, size_t chunk) {
  uint8_t out[64];
  uint64_t acc64[8];
  uint32_t acc32[8];
  uint8_t block[128];
  size_t tot;
  uint8_t *salt = v->salted ? saltbuf : (uint8_t *)zeros;
  uint8_t *pers = v->personal ? persbuf : (uint8_t *)zeros;
  memset(out, 0, sizeof out);
  if (v->alg == 'b') {
    Hacl_Streaming_Blake2_blake2b_params_init(acc64, block, &tot, keybuf,
                                              v->kl, v->nn, salt, pers,
                                              v->fanout, v->depth, v->leaf,
                                              v->off, v->nd, v->il);
    for (size_t i = 0; i < v->ml; i += chunk) {
      size_t n = v->ml - i < chunk ? v->ml - i : chunk;
      Hacl_Streaming_Blake2_blake2b_params_update(acc64, block, &tot, buf + i,
                                                  n);
    }
    Hacl_Streaming_Blake2_blake2b_params_digest(acc64, block, &tot, out,
                                                v->nn);
  } else {
    Hacl_Streaming_Blake2_blake2s_params_init(acc32, block, &tot, keybuf,
                                              v->kl, v->nn, salt, pers,
                                              v->fanout, v->depth, v->leaf,
                                              v->off, v->nd, v->il);
    for (size_t i = 0; i < v->ml; i += chunk) {
      size_t n = v->ml - i < chunk ? v->ml - i : chunk;
      Hacl_Streaming_Blake2_blake2s_params_update(acc32, block, &tot, buf + i,
                                                  n);
    }
    Hacl_Streaming_Blake2_blake2s_params_digest(acc32, block, &tot, out,
                                                v->nn);
  }
  char what[32];
  snprintf(what, sizeof what, "streaming/%zu", chunk);
  report(what, idx, out, v->nn, v->expected);
}

/* Default parameters must reproduce the named fixed-length functions. */
static void defaults_match_named(void) {
  uint8_t a[64], b[64];
  size_t ml = 300, kl = 17;
  Hacl_Hash_Blake2_Named_blake2b_512(a, keybuf, kl, buf, ml);
  Hacl_Hash_Blake2_Named_blake2b_params(b, 64, keybuf, kl, buf, ml,
                                        (uint8_t *)zeros, (uint8_t *)zeros,
                                        1, 1, 0, 0, 0, 0);
  if (memcmp(a, b, 64)) {
    printf("  FAIL blake2b defaults != blake2b_512\n");
    failures++;
  }
  Hacl_Hash_Blake2_Named_blake2b_256(a, keybuf, kl, buf, ml);
  Hacl_Hash_Blake2_Named_blake2b_params(b, 32, keybuf, kl, buf, ml,
                                        (uint8_t *)zeros, (uint8_t *)zeros,
                                        1, 1, 0, 0, 0, 0);
  if (memcmp(a, b, 32)) {
    printf("  FAIL blake2b defaults != blake2b_256\n");
    failures++;
  }
  Hacl_Hash_Blake2_Named_blake2s_256(a, keybuf, kl, buf, ml);
  Hacl_Hash_Blake2_Named_blake2s_params(b, 32, keybuf, kl, buf, ml,
                                        (uint8_t *)zeros, (uint8_t *)zeros,
                                        1, 1, 0, 0, 0, 0);
  if (memcmp(a, b, 32)) {
    printf("  FAIL blake2s defaults != blake2s_256\n");
    failures++;
  }
  Hacl_Hash_Blake2_Named_blake2s_128(a, keybuf, kl, buf, ml);
  Hacl_Hash_Blake2_Named_blake2s_params(b, 16, keybuf, kl, buf, ml,
                                        (uint8_t *)zeros, (uint8_t *)zeros,
                                        1, 1, 0, 0, 0, 0);
  if (memcmp(a, b, 16)) {
    printf("  FAIL blake2s defaults != blake2s_128\n");
    failures++;
  }
}

int main(void) {
  static const size_t chunks[] = { 1, 7, 64, 128, 4096 };
  size_t n = sizeof vecs / sizeof vecs[0];

  for (size_t i = 0; i < sizeof buf; i++)
    buf[i] = (uint8_t)((i * 7 + 11) & 0xff);
  for (size_t i = 0; i < sizeof keybuf; i++)
    keybuf[i] = (uint8_t)((i * 3 + 5) & 0xff);
  for (size_t i = 0; i < sizeof saltbuf; i++)
    saltbuf[i] = (uint8_t)((i * 13 + 1) & 0xff);
  for (size_t i = 0; i < sizeof persbuf; i++)
    persbuf[i] = (uint8_t)((i * 29 + 17) & 0xff);

  for (size_t i = 0; i < n; i++) {
    one_shot(i, &vecs[i]);
    for (size_t c = 0; c < sizeof chunks / sizeof chunks[0]; c++)
      streaming(i, &vecs[i], chunks[c]);
  }
  defaults_match_named();

  if (failures) {
    printf("%d failure(s)\n", failures);
    return 1;
  }
  printf("all %zu BLAKE2 parameter-block vectors pass\n", n);
  return 0;
}
