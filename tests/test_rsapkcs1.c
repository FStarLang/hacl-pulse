static int expect(const char *name, const char *what, bool got, bool want) {
  if (got != want) {
    printf("  FAIL %s: %s: got %s\n", name, what, got ? "accept" : "reject");
    return 1;
  }
  return 0;
}

static int test_case(const char *name, uint32_t modBits, uint8_t *nb,
                     size_t eLen, uint8_t *eb, uint8_t *db, size_t mLen,
                     uint8_t *msg, uint8_t *sig, sign_t sign, verify_t verify,
                     verify_t other) {
  int r = 0;
  size_t k = (modBits + 7) / 8;
  uint8_t *buf = malloc(k);
  uint8_t *m2 = malloc(mLen + 1);

  memset(buf, 0, k);
  r |= expect(name, "signing", sign(modBits, nb, k, db, mLen, msg, buf), true);
  if (memcmp(buf, sig, k) != 0) {
    printf("  FAIL %s: signature differs from OpenSSL's\n", name);
    r = 1;
  }

  r |= expect(name, "valid signature",
              verify(modBits, nb, eLen, eb, sig, mLen, msg), true);
  r |= expect(name, "other hash",
              other(modBits, nb, eLen, eb, sig, mLen, msg), false);

  for (size_t i = 0; i < k; i += k / 7 + 1) {
    memcpy(buf, sig, k);
    buf[i] ^= 0x01;
    r |= expect(name, "flipped signature bit",
                verify(modBits, nb, eLen, eb, buf, mLen, msg), false);
  }

  memcpy(m2, msg, mLen);
  m2[mLen] = 0x00;
  r |= expect(name, "extended message",
              verify(modBits, nb, eLen, eb, sig, mLen + 1, m2), false);
  if (mLen > 0) {
    m2[0] ^= 0x80;
    r |= expect(name, "modified message",
                verify(modBits, nb, eLen, eb, sig, mLen, m2), false);
  }

  /* The signature must be less than the modulus: s = n and s = 0. */
  r |= expect(name, "signature equal to modulus",
              verify(modBits, nb, eLen, eb, nb, mLen, msg), false);
  memset(buf, 0, k);
  r |= expect(name, "zero signature",
              verify(modBits, nb, eLen, eb, buf, mLen, msg), false);

  /* An even modulus is rejected, by both directions. */
  memcpy(buf, nb, k);
  buf[k - 1] ^= 0x01;
  r |= expect(name, "even modulus",
              verify(modBits, buf, eLen, eb, sig, mLen, msg), false);
  uint8_t *out = malloc(k);
  r |= expect(name, "signing with an even modulus",
              sign(modBits, buf, k, db, mLen, msg, out), false);
  free(out);

  free(buf);
  free(m2);
  return r;
}

static int test_malformed(void) {
  int r = 0;
  const char *name = "a (malformed encodings)";
  struct { const char *what; uint8_t *sig; } bad[] = {
    { "DigestInfo without NULL", bad_nonull_a },
    { "garbage after the digest", bad_garbage_a },
    { "block type 2", bad_bt2_a },
    { "padding byte 0xfe", bad_psbyte_a },
    { "wrong DigestInfo", bad_wrongdi_a },
  };
  for (size_t i = 0; i < sizeof(bad) / sizeof(bad[0]); i++)
    r |= expect(name, bad[i].what,
                Hacl_RSAPKCS1_verify_sha256(2048, n_a, sizeof(e_a), e_a,
                                            bad[i].sig, sizeof(msg_a), msg_a),
                false);
  /* A 512-bit (64-byte) modulus is too small for a sha512 encoding, which
   * needs 11 + 19 + 64 bytes.  Only the first 64 bytes of n_a are read. */
  r |= expect(name, "modulus too small for sha512",
              Hacl_RSAPKCS1_verify_sha512(512, n_a, sizeof(e_a), e_a,
                                          sig_a, sizeof(msg_a), msg_a),
              false);
  uint8_t out[64];
  r |= expect(name, "signing with a modulus too small for sha512",
              Hacl_RSAPKCS1_sign_sha512(512, n_a, 64, d_a, sizeof(msg_a),
                                        msg_a, out),
              false);
  return r;
}

