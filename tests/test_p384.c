static int expect(const char *name, bool got, bool want) {
  if (got != want) {
    printf("  FAIL %s: got %s\n", name, got ? "true" : "false");
    return 1;
  }
  printf("  ok   %s\n", name);
  return 0;
}

static int same(const char *name, const uint8_t *got, const uint8_t *want,
                size_t n) {
  return expect(name, memcmp(got, want, n) == 0, true);
}

static bool sgn(uint8_t *out, const char *msg, const uint8_t *key,
                const uint8_t *nonce) {
  return Hacl_P384_ecdsa_sign_sha384(out, (uint8_t *)msg, strlen(msg),
                                     (uint8_t *)key, (uint8_t *)nonce);
}

static bool vfy(const char *msg, const uint8_t *pub, const uint8_t *sig) {
  return Hacl_P384_ecdsa_verify_sha384((uint8_t *)msg, strlen(msg),
                                       (uint8_t *)pub, (uint8_t *)sig);
}

static bool sgn256(uint8_t *out, const char *msg, const uint8_t *key,
                   const uint8_t *nonce) {
  return Hacl_P384_ecdsa_sign_sha256(out, (uint8_t *)msg, strlen(msg),
                                     (uint8_t *)key, (uint8_t *)nonce);
}

static bool vfy256(const char *msg, const uint8_t *pub, const uint8_t *sig) {
  return Hacl_P384_ecdsa_verify_sha256((uint8_t *)msg, strlen(msg),
                                       (uint8_t *)pub, (uint8_t *)sig);
}

/* out = n - a, for 48-byte big-endian a < n. */
static void neg_mod_n(uint8_t *out, const uint8_t *a) {
  int borrow = 0;
  for (int i = 47; i >= 0; i--) {
    int d = (int)order[i] - (int)a[i] - borrow;
    borrow = d < 0;
    out[i] = (uint8_t)(d + (borrow ? 256 : 0));
  }
}

